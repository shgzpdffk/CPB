class ParsedPrefer_ind(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    ingredients: list[str]
class ParsedPrefer(BaseModel):

    model_config = ConfigDict(extra="forbid", strict=True)
    max_cooking_minutes :int |None = Field(gt = 0)
class parsedDish(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    Dish : str
